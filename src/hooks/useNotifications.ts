import { useCallback, useMemo } from "react";
import { useQuery, useQueryClient } from "@tanstack/react-query";
import { supabase } from "@/integrations/supabase/client";
import { useAuth } from "./useAuth";

export interface AppNotification {
  id: string;
  category: "order" | "other";
  type: string;
  title: string;
  body: string | null;
  link_url: string | null;
  read_at: string | null;
  created_at: string;
}

const COLUMNS = "id, category, type, title, body, link_url, read_at, created_at";
const LIMIT = 50;
// Checked every 2 minutes while the tab is in view (not in a hidden tab),
// and when the tab comes back into view after a minute or more.
const POLL_MS = 2 * 60_000;
// Between full reloads only notifications newer than the newest one held
// are fetched - usually none. The full reload also picks up ones marked
// read on another device.
const FULL_RELOAD_MS = 10 * 60_000;
// The bell and the new-orders banner share one copy; this stops their two
// timers from both fetching.
const MIN_GAP_MS = 20_000;

interface NotificationCache {
  items: AppNotification[];
  fullAt: number;
}

// Two-area notification center: "order" (new order, cancellation, return,
// vendor confirmation, unconfirmed reminder - all generated by DB
// triggers/a cron job, see the notifications migration) and "other" (a
// general bucket, wired and ready, currently unpopulated). Polls rather
// than using Supabase Realtime - simplest reliable way to get "visible
// without an extra click" without adding a new moving part this pass.
// It used to fetch all 50 every 30 s in each component that showed them
// (~42k calls on 27 Nov 2026).
export function useNotifications() {
  const { user } = useAuth();
  const queryClient = useQueryClient();
  const queryKey = useMemo(() => ["notifications", user?.id], [user?.id]);

  const { data, isPending, refetch } = useQuery({
    queryKey,
    enabled: !!user,
    staleTime: 60_000,
    refetchInterval: POLL_MS,
    queryFn: async (): Promise<NotificationCache> => {
      const held = queryClient.getQueryData<NotificationCache>(queryKey);
      const heldAt = queryClient.getQueryState(queryKey)?.dataUpdatedAt ?? 0;
      if (held && Date.now() - heldAt < MIN_GAP_MS) return held;

      const newest = held?.items[0]?.created_at;
      if (held && newest && Date.now() - held.fullAt < FULL_RELOAD_MS) {
        const { data, error } = await supabase
          .from("notifications")
          .select(COLUMNS)
          .gt("created_at", newest)
          .order("created_at", { ascending: false })
          .limit(LIMIT);
        if (error) throw error;
        // Re-read: a mark-as-read may have changed the copy meanwhile.
        const current = queryClient.getQueryData<NotificationCache>(queryKey) ?? held;
        if (!data?.length) return current;
        const fresh = data as AppNotification[];
        const freshIds = new Set(fresh.map((n) => n.id));
        return {
          items: [...fresh, ...current.items.filter((n) => !freshIds.has(n.id))].slice(0, LIMIT),
          fullAt: current.fullAt,
        };
      }

      const { data, error } = await supabase
        .from("notifications")
        .select(COLUMNS)
        .order("created_at", { ascending: false })
        .limit(LIMIT);
      if (error) throw error;
      return { items: (data ?? []) as AppNotification[], fullAt: Date.now() };
    },
  });

  const notifications = user ? (data?.items ?? []) : [];

  // Changes the copy on screen at once. A fetch still on its way is
  // dropped first, so it can't put back the old "unread".
  const patchItems = useCallback(
    async (change: (items: AppNotification[]) => AppNotification[]) => {
      await queryClient.cancelQueries({ queryKey });
      queryClient.setQueryData<NotificationCache>(queryKey, (prev) =>
        prev ? { ...prev, items: change(prev.items) } : prev,
      );
    },
    [queryClient, queryKey],
  );

  const markRead = async (id: string) => {
    const now = new Date().toISOString();
    await patchItems((items) => items.map((n) => (n.id === id ? { ...n, read_at: now } : n)));
    await supabase.from("notifications").update({ read_at: now }).eq("id", id);
  };

  const markAllRead = async (category: "order" | "other") => {
    const now = new Date().toISOString();
    const ids = notifications.filter((n) => n.category === category && !n.read_at).map((n) => n.id);
    if (ids.length === 0) return;
    await patchItems((items) => items.map((n) => (ids.includes(n.id) ? { ...n, read_at: now } : n)));
    await supabase.from("notifications").update({ read_at: now }).in("id", ids);
  };

  const orderNotifications = notifications.filter((n) => n.category === "order");
  const otherNotifications = notifications.filter((n) => n.category === "other");

  return {
    orderNotifications,
    otherNotifications,
    unreadOrderCount: orderNotifications.filter((n) => !n.read_at).length,
    unreadOtherCount: otherNotifications.filter((n) => !n.read_at).length,
    markRead,
    markAllRead,
    loading: !!user && isPending,
    refetch: async () => {
      await refetch();
    },
  };
}
