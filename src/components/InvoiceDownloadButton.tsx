import { useEffect, useState } from "react";
import { Button } from "@/components/ui/button";
import { Dialog, DialogContent, DialogHeader, DialogTitle } from "@/components/ui/dialog";
import { Loader2, Printer, FileText } from "lucide-react";
import { format } from "date-fns";
import { invokeEdgeFunction } from "@/lib/invokeEdgeFunction";
import { amountInWords } from "@/lib/amountInWords";
import { COMPANY } from "@/lib/company";
import { printElement } from "@/lib/printElement";

type Address = { address_line1?: string; address_line2?: string; city?: string; state?: string; pincode?: string } | null;

interface Invoice {
  invoice_number: string;
  issued_at: string;
  order_number: string | null;
  order_date: string | null;
  subtotal: number;
  shipping_cost: number;
  discount_code: string | null;
  discount_amount: number;
  taxable_value: number | null;
  cgst_amount: number;
  sgst_amount: number;
  igst_amount: number;
  tax_amount: number;
  total: number;
  supply_type: "intra_state" | "inter_state" | null;
  seller_name: string;
  seller_legal_name: string | null;
  seller_gstin: string | null;
  seller_pan: string | null;
  seller_address: Address;
  seller_state: string | null;
  seller_state_code: string | null;
  billing_name: string;
  billing_address: Address;
  billing_state: string | null;
  place_of_supply_code: string | null;
}

interface InvoiceLine {
  line_no: number;
  description: string;
  hsn_code: string | null;
  size: string | null;
  color: string | null;
  quantity: number;
  unit_price: number;
  discount: number;
  taxable_value: number;
  gst_rate: number;
  cgst_amount: number;
  sgst_amount: number;
  igst_amount: number;
  total: number;
}

const money = (n: number) => Number(n).toLocaleString("en-IN", { minimumFractionDigits: 2, maximumFractionDigits: 2 });
const pct = (n: number) => `${Number(n)}%`;
const addressLines = (a: Address) =>
  a ? [[a.address_line1, a.address_line2].filter(Boolean).join(", "), [a.city, a.pincode].filter(Boolean).join(" - ")].filter(Boolean) : [];

// Statuses where a Cash on Delivery item's goods are on their way to the
// customer, so its invoice can be issued (the server checks the same,
// including the warehouse quality check).
const COD_INVOICE_STATUSES = ["at_warehouse", "shipped", "out_for_delivery", "delivered", "ndr"];

interface InvoiceDownloadButtonProps {
  vendorOrderId: string;
  paymentStatus: string;
  vendorOrderStatus?: string;
}

// The boutique's GST tax invoice to the customer (generated by AllBoutiqs
// on its behalf - see generate-invoice). Opens in a dialog that prints /
// saves as PDF with the browser.
export function InvoiceDownloadButton({ vendorOrderId, paymentStatus, vendorOrderStatus }: InvoiceDownloadButtonProps) {
  const [open, setOpen] = useState(false);
  const [loading, setLoading] = useState(false);
  const [invoice, setInvoice] = useState<Invoice | null>(null);
  const [lines, setLines] = useState<InvoiceLine[]>([]);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    if (!open || invoice || loading) return;
    setLoading(true);
    setError(null);
    invokeEdgeFunction<{ invoice: Invoice; lines: InvoiceLine[] }>("generate-invoice", { vendor_order_id: vendorOrderId }).then(
      ({ data, errorMessage }) => {
        if (errorMessage || !data) setError(errorMessage || "Could not generate invoice");
        else {
          setInvoice(data.invoice);
          setLines(data.lines ?? []);
        }
        setLoading(false);
      },
    );
  }, [open, invoice, loading, vendorOrderId]);

  if (vendorOrderStatus === "cancelled" || vendorOrderStatus === "qc_failed") {
    return <span className="text-xs text-muted-foreground">No invoice — item cancelled</span>;
  }
  const codReady = !!vendorOrderStatus && COD_INVOICE_STATUSES.includes(vendorOrderStatus);
  if (paymentStatus !== "paid" && !codReady) {
    return <span className="text-xs text-muted-foreground">Invoice available once shipped</span>;
  }

  const intra = invoice?.supply_type !== "inter_state";

  return (
    <>
      <Button variant="ghost" size="sm" className="h-7 gap-1 text-xs" onClick={() => setOpen(true)}>
        <FileText className="h-3.5 w-3.5" /> Invoice
      </Button>

      <Dialog open={open} onOpenChange={setOpen}>
        <DialogContent className="max-w-4xl max-h-[90vh] overflow-y-auto">
          <DialogHeader>
            <DialogTitle>Tax Invoice</DialogTitle>
          </DialogHeader>

          {loading ? (
            <div className="flex items-center justify-center py-10">
              <Loader2 className="h-6 w-6 animate-spin text-primary" />
            </div>
          ) : error ? (
            <p className="text-sm text-destructive py-6 text-center">{error}</p>
          ) : invoice ? (
            <div id="invoice-content" className="space-y-4 text-xs text-foreground">
              <div className="flex items-start justify-between gap-4 border-b-2 border-foreground pb-3">
                <div>
                  <p className="text-lg font-bold tracking-wide">TAX INVOICE</p>
                  <p className="text-muted-foreground">Original for recipient</p>
                </div>
                <div className="text-right space-y-0.5">
                  <p>
                    <span className="text-muted-foreground">Invoice No: </span>
                    <span className="font-mono font-semibold">{invoice.invoice_number}</span>
                  </p>
                  <p>
                    <span className="text-muted-foreground">Invoice Date: </span>
                    {format(new Date(invoice.issued_at), "dd MMM yyyy")}
                  </p>
                  {invoice.order_number && (
                    <p>
                      <span className="text-muted-foreground">Order No: </span>
                      {invoice.order_number}
                      {invoice.order_date && ` · ${format(new Date(invoice.order_date), "dd MMM yyyy")}`}
                    </p>
                  )}
                </div>
              </div>

              <div className="grid sm:grid-cols-2 gap-4">
                <div className="space-y-0.5">
                  <p className="text-[10px] uppercase tracking-wider text-muted-foreground">Sold by</p>
                  <p className="text-sm font-semibold">{invoice.seller_legal_name ?? invoice.seller_name}</p>
                  {invoice.seller_legal_name && invoice.seller_legal_name !== invoice.seller_name && (
                    <p className="text-muted-foreground">Trading as {invoice.seller_name}</p>
                  )}
                  {addressLines(invoice.seller_address).map((l) => (
                    <p key={l}>{l}</p>
                  ))}
                  <p>
                    State: {invoice.seller_state ?? "—"}
                    {invoice.seller_state_code && ` (${invoice.seller_state_code})`}
                  </p>
                  {invoice.seller_gstin && <p>GSTIN: <span className="font-mono">{invoice.seller_gstin}</span></p>}
                  {invoice.seller_pan && <p>PAN: <span className="font-mono">{invoice.seller_pan}</span></p>}
                </div>
                <div className="space-y-0.5">
                  <p className="text-[10px] uppercase tracking-wider text-muted-foreground">Bill to / Ship to</p>
                  <p className="text-sm font-semibold">{invoice.billing_name}</p>
                  {addressLines(invoice.billing_address).map((l) => (
                    <p key={l}>{l}</p>
                  ))}
                  <p>
                    State: {invoice.billing_state ?? invoice.billing_address?.state ?? "—"}
                    {invoice.place_of_supply_code && ` (${invoice.place_of_supply_code})`}
                  </p>
                  <p>
                    Place of supply: {invoice.billing_state ?? "—"}
                    {invoice.place_of_supply_code && ` (${invoice.place_of_supply_code})`}
                  </p>
                  <p>Tax payable on reverse charge: No</p>
                </div>
              </div>

              <div className="invoice-scroll overflow-x-auto">
                <table className="w-full border-collapse text-[11px]">
                  <thead>
                    <tr className="border-y border-foreground text-left">
                      <th className="py-1.5 pr-2">#</th>
                      <th className="py-1.5 pr-2">Description</th>
                      <th className="py-1.5 pr-2">HSN</th>
                      <th className="py-1.5 pr-2">Size</th>
                      <th className="py-1.5 pr-2 text-right">Qty</th>
                      <th className="py-1.5 pr-2 text-right">Price (incl. GST)</th>
                      <th className="py-1.5 pr-2 text-right">Discount</th>
                      <th className="py-1.5 pr-2 text-right">Taxable value</th>
                      {intra ? (
                        <>
                          <th className="py-1.5 pr-2 text-right">CGST</th>
                          <th className="py-1.5 pr-2 text-right">SGST</th>
                        </>
                      ) : (
                        <th className="py-1.5 pr-2 text-right">IGST</th>
                      )}
                      <th className="py-1.5 text-right">Total</th>
                    </tr>
                  </thead>
                  <tbody>
                    {lines.map((l) => (
                      <tr key={l.line_no} className="border-b border-border align-top">
                        <td className="py-1.5 pr-2">{l.line_no}</td>
                        <td className="py-1.5 pr-2">
                          {l.description}
                          {l.color && <span className="text-muted-foreground"> · {l.color}</span>}
                        </td>
                        <td className="py-1.5 pr-2 font-mono">{l.hsn_code ?? "—"}</td>
                        <td className="py-1.5 pr-2">{l.size ?? "—"}</td>
                        <td className="py-1.5 pr-2 text-right">{l.quantity}</td>
                        <td className="py-1.5 pr-2 text-right">{money(l.unit_price)}</td>
                        <td className="py-1.5 pr-2 text-right">{Number(l.discount) ? money(l.discount) : "—"}</td>
                        <td className="py-1.5 pr-2 text-right">{money(l.taxable_value)}</td>
                        {intra ? (
                          <>
                            <td className="py-1.5 pr-2 text-right whitespace-nowrap">
                              {pct(Number(l.gst_rate) / 2)} · {money(l.cgst_amount)}
                            </td>
                            <td className="py-1.5 pr-2 text-right whitespace-nowrap">
                              {pct(Number(l.gst_rate) / 2)} · {money(l.sgst_amount)}
                            </td>
                          </>
                        ) : (
                          <td className="py-1.5 pr-2 text-right whitespace-nowrap">
                            {pct(l.gst_rate)} · {money(l.igst_amount)}
                          </td>
                        )}
                        <td className="py-1.5 text-right font-medium">{money(l.total)}</td>
                      </tr>
                    ))}
                  </tbody>
                </table>
              </div>

              <div className="flex flex-col sm:flex-row justify-between gap-4">
                <p className="sm:max-w-[55%]">
                  <span className="text-muted-foreground">Amount in words: </span>
                  {amountInWords(invoice.total)}
                </p>
                <div className="space-y-1 sm:min-w-[240px]">
                  <div className="flex justify-between">
                    <span className="text-muted-foreground">Taxable value</span>
                    <span>₹{money(invoice.taxable_value ?? invoice.total - invoice.tax_amount)}</span>
                  </div>
                  {intra ? (
                    <>
                      <div className="flex justify-between">
                        <span className="text-muted-foreground">CGST</span>
                        <span>₹{money(invoice.cgst_amount)}</span>
                      </div>
                      <div className="flex justify-between">
                        <span className="text-muted-foreground">SGST</span>
                        <span>₹{money(invoice.sgst_amount)}</span>
                      </div>
                    </>
                  ) : (
                    <div className="flex justify-between">
                      <span className="text-muted-foreground">IGST</span>
                      <span>₹{money(invoice.igst_amount)}</span>
                    </div>
                  )}
                  <div className="flex justify-between border-t border-foreground pt-1 text-sm font-bold">
                    <span>Total (incl. GST)</span>
                    <span>₹{money(invoice.total)}</span>
                  </div>
                  {Number(invoice.discount_amount) > 0 && (
                    <p className="text-[10px] text-muted-foreground text-right">
                      Includes this item's share of the order discount
                      {invoice.discount_code && ` (${invoice.discount_code})`}: ₹{money(invoice.discount_amount)}
                    </p>
                  )}
                </div>
              </div>

              <div className="border-t border-border pt-3 space-y-1 text-[11px]">
                <p className="font-medium">
                  Sold through {COMPANY.legalName}, GSTIN {COMPANY.gstin}
                </p>
                <p>Returns and exchanges as per the AllBoutiqs return policy (allboutiqs.com).</p>
                <p>
                  Customer care: {COMPANY.supportEmail} · {COMPANY.supportPhone} · WhatsApp {COMPANY.whatsapp}
                </p>
                <p>Subject to {COMPANY.jurisdiction} jurisdiction.</p>
                <p className="text-muted-foreground">
                  This is a computer-generated invoice issued on behalf of the seller and does not need a signature.
                </p>
              </div>

              <Button
                onClick={() => printElement(document.getElementById("invoice-content"), `Invoice ${invoice.invoice_number}`)}
                className="w-full gap-2 print:hidden"
              >
                <Printer className="h-4 w-4" /> Print / Save as PDF
              </Button>
            </div>
          ) : null}
        </DialogContent>
      </Dialog>
    </>
  );
}
